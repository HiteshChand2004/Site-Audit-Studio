/**
 * The recreate's evidence for a check: the fixer entries and auto-generated values behind it.
 * @returns {{ evidence: object[], review: boolean } | null}  review: some value was auto-generated
 */
export function evidenceFor(key, report) {
  const rule = EVIDENCE[key];
  if (!rule) return null;
  const evidence = [];
  for (const id of rule.fixes ?? []) {
    const fix = (report.fixes ?? []).find((f) => f.id === id);
    if (fix) evidence.push({ fix: fix.id, title: fix.title, status: fix.status, count: fix.count ?? null, open: fix.open ?? 0 });
  }
  const auto = (report.autoGenerated ?? []).filter((a) => rule.auto?.includes(a.field));
  if (auto.length) {
    evidence.push({
      autoGenerated: auto.length,
      fields: [...new Set(auto.map((a) => a.field))],
      examples: auto.slice(0, 3).map((a) => ({ page: a.page ?? null, field: a.field, value: a.value, source: a.source })),
    });
  }
  return evidence.length ? { evidence, review: auto.length > 0 } : null;
}

/**
 * The checklist status of one check.
 * @param {{ rank: number, count?: number, score?: number } | null} before  OLD (rank 0 = passes)
 * @param {{ rank: number, count?: number, score?: number } | null} after   NEW
 */
export function classify(before, after) {
  if (!after) return 'na';
  if (!before) return after.rank ? 'open' : 'pass';
  if (!before.rank && !after.rank) return 'pass';
  if (!after.rank) return 'fixed';
  if (!before.rank || after.rank > before.rank) return 'regressed';
  if (after.rank < before.rank) return 'improved';
  // Same severity: fewer affected things (or a better Lighthouse score) is an improvement.
  if (before.count != null && after.count != null && after.count < before.count) return 'improved';
  if (before.score != null && after.score != null && after.score - before.score >= 0.05) return 'improved';
  return 'open';
}

export const rankOfStatus = (status) => ({ pass: 0, warn: 1, fail: 2 })[status] ?? 0;
export const rankOfScore = (score) => (score >= 0.9 ? 0 : score >= 0.5 ? 1 : 2);
export const rankOfImpact = (impact) => (impact === 'critical' || impact === 'serious' ? 2 : 1);
