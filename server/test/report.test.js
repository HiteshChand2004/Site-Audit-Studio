test('the logo is read from the project\'s saved icon; anything that is not an image is ignored', async () => {
  const id = makeProject('Logo Co', 'https://logo.example/');
  const dir = projectDir(id);
  await mkdir(dir, { recursive: true });
  assert.equal(await logo(id), null, 'no icon yet');
  await writeFile(path.join(dir, 'favicon.bin'), await sharp({ create: { width: 8, height: 8, channels: 3, background: '#c2410c' } }).png().toBuffer());
  await writeFile(path.join(dir, 'favicon.json'), JSON.stringify({ type: 'image/png' }));
  assert.match(await logo(id), /^data:image\/png;base64,/);
  const html = await (await fetch(`${base}/${id}/report`)).text();
  assert.match(html, /<span class="logo"><img src="data:image\/png;base64,/);
  await writeFile(path.join(dir, 'favicon.json'), JSON.stringify({ type: 'text/html' }));
  assert.equal(await logo(id), null);
});

test('download and JSON formats', async () => {
  const id = makeProject('Shop', 'https://shop.example/');
  addAnalysis(id, { ...AUDIT, url: 'https://shop.example/' });
  const html = await fetch(`${base}/${id}/report?download=1`);
  assert.match(html.headers.get('content-disposition'), /^attachment; filename="shop\.example-audit-report-\d{4}-\d{2}-\d{2}\.html"$/);
  await html.text();

  const json = await fetch(`${base}/${id}/report?format=json&download=1`);
  assert.match(json.headers.get('content-disposition'), /\.json"$/);
  assert.match(json.headers.get('content-type'), /application\/json/);
  const body = JSON.parse(await json.text());
  assert.equal(body.project.name, 'Shop');
  assert.equal(body.audit.techStack[0].name, 'WordPress');
  assert.equal(body.images, undefined, 'the screenshots belong to the HTML report only');
  assert.equal(body.recreate, null);
});

test('screenshots are embedded as small data URIs; a missing file is simply left out', async () => {
  const dir = path.join(projectDir(randomUUID()));
  await mkdir(dir, { recursive: true });
  const file = path.join(dir, 'shot.png');
  await sharp({ create: { width: 1440, height: 3000, channels: 3, background: '#6d4aff' } }).png().toFile(file);
  try {
    const uri = await thumbnail(file, 'desktop');
    assert.match(uri, /^data:image\/webp;base64,/);
    const meta = await sharp(Buffer.from(uri.split(',')[1], 'base64')).metadata();
    assert.equal(meta.width, 480);
    assert.equal(meta.height, 300, 'the first screen only (900 / 1440 of the width)');
    assert.ok(uri.length < 60000, 'small: the report must not get heavy');
    assert.equal(await thumbnail(path.join(dir, 'nope.png'), 'mobile'), null);
    // The recreated pictures come from the recreate folder of the latest recreate.
    const html = renderReportHtml({
      generatedAt: now(), project: { name: 'X', url: 'https://x.test/' }, audit: { ...AUDIT, recreate: null }, analyzed: true, recreate: RECREATE,
      images: { old: { desktop: uri }, new: { desktop: uri } },
    });
    assert.equal(html.split('data:image/webp;base64,').length - 1, 2, 'one small picture of the original and one of the recreate, nothing else');
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('PDF: a real PDF made by the server, no print dialog, two A4 pages', async () => {
  const id = makeProject('Pdf Co', 'https://pdf.example/');
  addAnalysis(id, { ...AUDIT, url: 'https://pdf.example/' });
  addRecreate(id);
  const res = await fetch(`${base}/${id}/report?format=pdf&download=1`);
  assert.equal(res.status, 200);
  assert.equal(res.headers.get('content-type'), 'application/pdf');
  assert.match(res.headers.get('content-disposition'), /^attachment; filename="pdf\.example-audit-report-\d{4}-\d{2}-\d{2}\.pdf"$/);
  const body = Buffer.from(await res.arrayBuffer());
  assert.equal(body.subarray(0, 5).toString(), '%PDF-');
  assert.ok(body.length > 8000, `${body.length} bytes`);
  const pages = body.toString('latin1').match(/\/Type \/Page[^s]/g) ?? [];
  assert.equal(pages.length, 2, `${pages.length} pages: a checked and copied site fits on two A4 pages`);
});
