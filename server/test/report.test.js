let server;
let base;
const projectIds = [];

before(async () => {
  const app = express();
  app.use('/api/projects', reportRouter);
  await new Promise((resolve) => {
    server = app.listen(0, '127.0.0.1', resolve);
  });
  base = `http://127.0.0.1:${server.address().port}/api/projects`;
});
after(async () => {
  await new Promise((resolve) => server.close(resolve));
  for (const id of projectIds) {
    db.prepare('DELETE FROM projects WHERE id = ?').run(id);
    await rm(projectDir(id), { recursive: true, force: true });
  }
});

const now = () => new Date().toISOString();
function makeProject(name = 'Acme', url = 'https://www.acme.test/') {
  const id = randomUUID();
  projectIds.push(id);
  db.prepare(`INSERT INTO projects (id, name, url, stack, authorized, created_at, updated_at) VALUES (?, ?, ?, 'html', 1, ?, ?)`).run(id, name, url, now(), now());
  return id;
}

