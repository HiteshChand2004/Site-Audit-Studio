// The re-audit of an as-is copy (reaudit/index.js): the copy runs the original's own scripts, so it is measured with them
// running (served as its preview serves it), and every row that got worse carries its reason or is marked unexplained.
// Before: the copy was served with the preview's policy, which blocks every script, so a page its script draws read as empty.
import { after, test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { runAnalysis } from '../src/audit/index.js';
import { db, projectDir } from '../src/db/index.js';
import { runReaudit } from '../src/reaudit/index.js';
import { servePreview } from '../src/recreate/preview.js';
import { recreateDir } from '../src/recreate/workspace.js';
import { createNetPolicy } from '../src/security/netGuard.js';
import { seedAnalysis, seedProject } from './helpers/projects.js';

delete process.env.SAS_ALLOW_LOCALHOST;
const FAST_SKIP = ['screenshots', 'lighthouse-mobile', 'lighthouse-desktop'];

// A page drawn by its own script (an app shell), with a link to a second page of the site.
const SHELL = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width">
<title>Acme — tools for builders</title><meta name="description" content="Acme makes tools for people who build things, made to last and easy to use every day.">
</head><body><div id="root"></div><script src="/app.js"></script></body></html>`;
const APP = `document.getElementById('root').innerHTML = '<main><h1>Acme tools</h1><p>' + 'Tools for people who build things. '.repeat(20) + '</p><a href="/pricing">Pricing</a></main>';`;
const PRICING = '<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Pricing — Acme</title></head><body><h1>Pricing</h1><a href="/">Home</a></body></html>';

async function writeTree(root, files) {
  for (const [rel, body] of Object.entries(files)) {
    await mkdir(path.dirname(path.join(root, rel)), { recursive: true });
    await writeFile(path.join(root, rel), body);
  }
}

const projectIds = [];
after(async () => {
  for (const id of projectIds) {
    db.prepare('DELETE FROM projects WHERE id = ?').run(id);
    await rm(projectDir(id), { recursive: true, force: true });
  }
});

test('an as-is copy is re-audited with its own scripts running, and each row that got worse has a reason or says it has none', { timeout: 240000 }, async () => {
  const id = randomUUID();
  projectIds.push(id);
  seedProject(db, { id, name: 'acme', url: 'https://example.com/', stack: 'html', authorized: 1 });
  const project = db.prepare('SELECT * FROM projects WHERE id = ?').get(id);
  const originalRoot = path.join(projectDir(id), 'original-site');
  await writeTree(originalRoot, { 'index.html': SHELL, 'app.js': APP, 'pricing/index.html': PRICING });

  // The original analysed as it is served (scripts run, as on its own host).
  const original = await servePreview(originalRoot, { scripts: true });
  const analysisId = randomUUID();
  let originUrl;
  try {
    originUrl = original.origin;
    const audit = await runAnalysis({ project, analysisId, url: `${original.origin}/`, maxPages: 5, skip: FAST_SKIP, netPolicy: createNetPolicy({ internalPorts: [original.port] }), progress: () => {} });
    seedAnalysis(db, project.id, audit, { id: analysisId });
  } finally {
    await original.close();
  }

  // The as-is copy holds the homepage only (the pricing page was not chosen), with the original's own script.
  const recreateId = randomUUID();
  const rep = {
    recreateId, analysisId, baseUrl: originUrl, stack: 'html',
    pages: [{ url: `${originUrl}/`, outPath: 'index.html' }],
    asIs: { stack: 'html', mode: 'as-is', pages: [{ url: `${originUrl}/`, path: '/' }] },
    outputs: { html: { status: 'ready', dir: 'stacks/html', mode: 'as-is', pages: [{ outPath: 'index.html', path: '/' }] } },
    fixes: [], autoGenerated: [], manual: [], safety: { safe: true, mode: 'as-is' },
  };
  const now = new Date().toISOString();
  db.prepare(`INSERT INTO recreates (id, project_id, status, progress, started_at, finished_at, result_json) VALUES (?, ?, 'done', 100, ?, ?, ?)`).run(recreateId, project.id, now, now, JSON.stringify(rep));
  await writeTree(path.join(recreateDir(project.id, recreateId), 'stacks', 'html'), { 'index.html': SHELL, 'app.js': APP });

  const result = await runReaudit({ project: { ...project, url: `${originUrl}/` }, reauditId: randomUUID(), recreateId, progress: () => {}, skip: FAST_SKIP });
  const items = result.checklist.items;
  const h1 = items.find((i) => i.key === 'seo.headings.none');
  assert.ok(!h1 || h1.status !== 'regressed', 'the heading the script draws is there: the copy was measured with its script running');

  const worse = items.filter((i) => i.status === 'regressed');
  assert.ok(result.checklist.gotWorse, 'an as-is copy gets the reasons summary');
  assert.equal(result.checklist.gotWorse.total, worse.length, 'every row that got worse is counted, none left out');
  for (const w of worse) assert.ok(w.reason || w.unexplained, `${w.key} has a reason or is marked unexplained`);
  const links = worse.find((i) => i.key === 'links.broken-new');
  assert.ok(links, 'the link to the page that was not copied is broken in the copy');
  assert.equal(links.reason, 'owner');
  assert.match(links.reasonEvidence, /^These pages of your site were not copied: \/pricing\. .*"page not found" error \(404\)/);
});
